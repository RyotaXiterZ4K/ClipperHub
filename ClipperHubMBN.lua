local PROGRAM = {1, 2, 3, 4, 5}

local VM = {
    ip = 1,
    stack = {},
    registers = {},
    halted = false
}

local function push(value)
    VM.stack[#VM.stack + 1] = value
end

local function pop()
    local n = #VM.stack
    if n == 0 then
        error("ClipperHub VM: stack underflow", 0)
    end
    local value = VM.stack[n]
    VM.stack[n] = nil
    return value
end

local function decode(data)
    local chars = table.create(#data)
    local state = 173

    for i = 1, #data do
        state = (state * 73 + 41 + (i % 251)) % 256
        chars[i] = string.char((data[i] - state - (i % 97)) % 256)
    end

    return table.concat(chars)
end

local function dispatch(opcode)
    if opcode == 1 then
        push(PAYLOAD)
    elseif opcode == 2 then
        local data = pop()
        push(decode(data))
    elseif opcode == 3 then
        local source = pop()
        local compiler = loadstring
        if type(compiler) ~= "function" then
            error("ClipperHub VM: loadstring is unavailable", 0)
        end

        local chunk, compileError = compiler(source)
        if not chunk then
            error("ClipperHub VM compile error: " .. tostring(compileError), 0)
        end
        push(chunk)
    elseif opcode == 4 then
        local chunk = pop()
        push(chunk())
    elseif opcode == 5 then
        VM.halted = true
    else
        error("ClipperHub VM: invalid opcode " .. tostring(opcode), 0)
    end
end

while not VM.halted do
    local opcode = PROGRAM[VM.ip]
    if opcode == nil then
        error("ClipperHub VM: instruction pointer out of range", 0)
    end

    VM.ip = VM.ip + 1
    dispatch(opcode)
end

return pop()
